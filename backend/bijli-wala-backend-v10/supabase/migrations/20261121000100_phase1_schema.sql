CREATE SCHEMA solar_app;
REVOKE ALL ON SCHEMA solar_app FROM PUBLIC;

CREATE TABLE solar_app.jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer text NOT NULL,
    phone text NOT NULL,
    site text NOT NULL,
    customer_needs text CHECK (length(customer_needs) <= 1000),
    roof_area_centi_m2 bigint CHECK (roof_area_centi_m2 >= 0),
    monthly_bill_paise bigint CHECK (monthly_bill_paise >= 0),
    grid_suitability text CHECK (grid_suitability IN ('suitable', 'unsuitable', 'unknown')),
    survey_notes text,
    survey_approved_at timestamptz,
    roof_direction text CHECK (roof_direction IN (
        'North', 'North-east', 'East', 'South-east', 'South', 'South-west', 'West', 'North-west'
    )),
    tilt_centi_degrees integer CHECK (tilt_centi_degrees BETWEEN 0 AND 9000),
    cable_centi_m bigint CHECK (cable_centi_m >= 0)
);

CREATE TABLE solar_app.catalogue_packages (
    code text PRIMARY KEY,
    name text NOT NULL,
    total_paise bigint NOT NULL CHECK (total_paise > 0)
);

CREATE TABLE solar_app.catalogue_parts (
    package_code text NOT NULL REFERENCES solar_app.catalogue_packages(code),
    position integer NOT NULL CHECK (position >= 0),
    name text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit text NOT NULL,
    warranty_years integer CHECK (warranty_years > 0),
    PRIMARY KEY (package_code, position),
    UNIQUE (package_code, name)
);

CREATE TABLE solar_app.quotes (
    job_id bigint PRIMARY KEY REFERENCES solar_app.jobs(id),
    package text NOT NULL,
    total_paise bigint NOT NULL CHECK (total_paise > 0),
    accepted_at timestamptz,
    catalogue_code text NOT NULL DEFAULT '3-on-grid'
);

CREATE TABLE solar_app.quote_parts (
    quote_id bigint NOT NULL REFERENCES solar_app.quotes(job_id),
    position integer NOT NULL CHECK (position >= 0),
    name text NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit text NOT NULL,
    warranty_years integer CHECK (warranty_years > 0),
    PRIMARY KEY (quote_id, position)
);

CREATE TABLE solar_app.advances (
    quote_id bigint PRIMARY KEY REFERENCES solar_app.quotes(job_id),
    amount_paise bigint NOT NULL CHECK (amount_paise > 0),
    recorded_at timestamptz NOT NULL DEFAULT statement_timestamp()
);

CREATE TABLE solar_app.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id bigint NOT NULL UNIQUE REFERENCES solar_app.advances(quote_id),
    confirmed_at timestamptz NOT NULL DEFAULT statement_timestamp()
);

CREATE TABLE solar_app.pick_lists (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES solar_app.orders(id)
);

CREATE TABLE solar_app.crew_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES solar_app.orders(id)
);
