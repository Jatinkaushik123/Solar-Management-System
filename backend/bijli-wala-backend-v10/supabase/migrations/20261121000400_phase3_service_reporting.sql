CREATE TABLE solar_app.service_tickets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_key text COLLATE "C" NOT NULL REFERENCES solar_app.serialized_units(serial_key),
    fault text NOT NULL CHECK (char_length(fault) BETWEEN 1 AND 2000),
    opened_on date NOT NULL,
    coverage text NOT NULL CHECK (coverage IN ('Covered', 'Expired')),
    parts_paise bigint CHECK (parts_paise >= 0 AND parts_paise < 100000000000),
    labour_paise bigint CHECK (labour_paise >= 0 AND labour_paise < 100000000000),
    customer_confirmed_at timestamptz,
    request_id text UNIQUE,
    CHECK ((parts_paise IS NULL) = (labour_paise IS NULL)),
    CHECK (coverage = 'Expired' OR parts_paise IS NULL),
    CHECK (customer_confirmed_at IS NULL OR coverage = 'Covered' OR parts_paise IS NOT NULL)
);

CREATE FUNCTION solar_app.protect_closed_ticket() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.customer_confirmed_at IS NOT NULL
       AND (NEW.parts_paise, NEW.labour_paise, NEW.customer_confirmed_at)
           IS DISTINCT FROM (OLD.parts_paise, OLD.labour_paise, OLD.customer_confirmed_at) THEN
        RAISE EXCEPTION 'This ticket is closed.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER protect_closed_ticket
BEFORE UPDATE OF parts_paise, labour_paise, customer_confirmed_at ON solar_app.service_tickets
FOR EACH ROW EXECUTE FUNCTION solar_app.protect_closed_ticket();

CREATE INDEX service_tickets_serial_idx ON solar_app.service_tickets (serial_key);
CREATE INDEX service_tickets_open_idx ON solar_app.service_tickets (opened_on, id)
    WHERE customer_confirmed_at IS NULL;

CREATE TABLE solar_app.job_costs (
    order_id bigint PRIMARY KEY REFERENCES solar_app.orders(id),
    materials_paise bigint CHECK (materials_paise >= 0 AND materials_paise < 100000000000),
    labour_paise bigint CHECK (labour_paise >= 0 AND labour_paise < 100000000000)
);

CREATE INDEX orders_confirmed_at_idx ON solar_app.orders (confirmed_at);
